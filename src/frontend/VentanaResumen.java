private void cargarResumen() {
    Rutina rutina = GestorEjercicios.getInstance().getRutinaActual();
    lblCliente.setText("Cliente: " + rutina.getNombreCliente() + 
                       "  |  Semana: " + rutina.getSemana());
    lblTotalVal.setText(String.valueOf(rutina.getTotalEjercicios()));
    lblCardioVal.setText(String.valueOf(rutina.contarPorTipo("Cardiovascular")));
    lblFuerzaVal.setText(String.valueOf(rutina.contarPorTipo("Fuerza")));
    lblBasicoVal.setText(String.valueOf(rutina.contarPorIntensidad(backend.NivelIntensidad.BASICO)));
    lblIntermedioVal.setText(String.valueOf(rutina.contarPorIntensidad(backend.NivelIntensidad.INTERMEDIO)));
    lblAvanzadoVal.setText(String.valueOf(rutina.contarPorIntensidad(backend.NivelIntensidad.AVANZADO)));
    lblAltoRendVal.setText(String.valueOf(rutina.contarPorIntensidad(backend.NivelIntensidad.ALTO_RENDIMIENTO)));
    lblTiempoVal.setText(rutina.getTiempoTotal() + " minutos");
}
