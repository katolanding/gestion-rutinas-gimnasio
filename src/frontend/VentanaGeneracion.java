    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        String cliente = txtCliente.getText().trim();
if (cliente.isEmpty()) {
    lblMensaje.setForeground(new java.awt.Color(220, 80, 80));
    lblMensaje.setText("Ingrese el nombre del cliente.");
    return;
}
int semana = (int) spnSemana.getValue();
int cantCardio = (int) spnCardio.getValue();
int cantFuerza = (int) spnFuerza.getValue();
backend.NivelIntensidad intCardio = backend.NivelIntensidad.values()[cmbIntensCardio.getSelectedIndex()];
backend.NivelIntensidad intFuerza = backend.NivelIntensidad.values()[cmbIntensFuerza.getSelectedIndex()];
backend.GestorEjercicios g = backend.GestorEjercicios.getInstance();
g.setSemanaActual(semana);
lblMensaje.setForeground(new java.awt.Color(108, 117, 125));
lblMensaje.setText("Generando...");
btnGenerar.setEnabled(false);
new Thread(() -> g.generarRutina(cantCardio, intCardio, cantFuerza, intFuerza, cliente)).start();
    }//GEN-LAST:event_btnGenerarActionPerformed

