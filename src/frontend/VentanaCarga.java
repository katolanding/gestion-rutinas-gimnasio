    @Override
public void onEjerciciosCargados(int total, int cardio, int fuerza,
        int basico, int intermedio, int avanzado, int altoRend, int tiempoTotal) {
    javax.swing.SwingUtilities.invokeLater(() -> {
        lblTotal.setText("Total: " + total);
        lblTiempo.setText("Tiempo: " + tiempoTotal + " min");
        lblCardio.setText("Cardiovascular: " + cardio);
        lblFuerza.setText("Fuerza: " + fuerza);
        lblBasico.setText("Básico: " + basico);
        lblIntermedio.setText("Intermedio: " + intermedio);
        lblAvanzado.setText("Avanzado: " + avanzado);
        lblAltoRend.setText("Alto rendimiento: " + altoRend);
        lblMensaje.setForeground(new java.awt.Color(100, 200, 100));
        lblMensaje.setText("✔ Ejercicios cargados.");
        btnIniciar.setEnabled(true);
    });
}

